import streamlit as st

st.set_page_config(
    page_title="AI MIL Trainer",
    page_icon="🧠",
    layout="wide",
)

MODULES = [
    ("01", "Основи ШІ", "Що таке ШІ, де він допомагає і де може помилятися.", 100),
    ("02", "Постановка задачі", "Як дати ШІ зрозуміле завдання.", 75),
    ("03", "Робота з інформацією", "Структурування, порівняння та аналіз.", 40),
    ("04", "Генерація альтернатив", "Як не зупинятися на першій ідеї.", 20),
    ("05", "Оцінювання", "Ризик, реалізованість, час і перевірюваність.", 0),
    ("06", "Критичне мислення", "Припущення, суперечності та пропущені ризики.", 0),
    ("07", "Прогнозування", "Сценарії та робота з невизначеністю.", 0),
    ("08", "Безпека та перевірка", "Людська перевірка і контроль результату.", 0),
]

st.title("🧠 AI MIL TRAINER")
st.caption("Інтерактивне навчання практичної роботи зі штучним інтелектом")

with st.sidebar:
    st.header("Навігація")
    page = st.radio(
        "Розділ",
        ["Dashboard", "Навчання", "Тренажер", "Перевірка", "Мій прогрес"],
    )
    st.divider()
    st.caption("Принцип: ШІ допомагає. Людина перевіряє.")

if page == "Dashboard":
    st.subheader("Панель навчання")

    c1, c2, c3, c4 = st.columns(4)
    c1.metric("Прогрес", "42%")
    c2.metric("Уроків", "8")
    c3.metric("Вправ", "12")
    c4.metric("Потребують уваги", "3")

    st.divider()
    left, right = st.columns([1.4, 1])

    with left:
        st.markdown("### Навчальна програма")
        for code, name, desc, progress in MODULES:
            st.markdown(f"**{code}. {name}**")
            st.caption(desc)
            st.progress(progress / 100)

    with right:
        st.markdown("### Карта навичок")
        skills = {
            "Основи ШІ": 0.82,
            "Постановка задач": 0.76,
            "Альтернативи": 0.54,
            "Критичне мислення": 0.48,
            "Перевірка": 0.61,
            "Оцінка ризику": 0.37,
        }
        for name, value in skills.items():
            st.write(name)
            st.progress(value)

elif page == "Навчання":
    st.subheader("📚 Навчання")
    st.info("Курс пояснює терміни простими словами та одразу дає практику.")

    module = st.selectbox("Оберіть модуль", [f"{x[0]}. {x[1]}" for x in MODULES])

    st.markdown("### Два режими мислення")
    a, b = st.columns(2)
    with a:
        st.success("🟢 РЕЖИМ 1 — ГЕНЕРУЙ")
        st.write("Створюй щонайменше 5 різних підходів. Не ранжуй їх на цьому етапі.")
    with b:
        st.warning("🔴 РЕЖИМ 2 — ОЦІНЮЙ")
        st.write("Після генерації порівнюй варіанти за наперед визначеними критеріями.")

    st.markdown("### Формула хорошого запиту")
    st.code("ЗАДАЧА → КОНТЕКСТ → РЕЗУЛЬТАТ → ОБМЕЖЕННЯ → ПЕРЕВІРКА")

    if st.button("Перейти до практики", type="primary"):
        st.session_state["page_hint"] = "trainer"
        st.success("Тренажер відкрито через меню зліва.")

elif page == "Тренажер":
    st.subheader("🎯 Практичний тренажер")
    st.write("Навчальна задача використовує умовні дані. Реальні чутливі дані сюди не вводяться.")

    task = st.text_area(
        "Завдання",
        value="Потрібно підготувати навчальний матеріал для групи слухачів.",
        height=100,
    )

    if st.button("🟢 Згенерувати альтернативи", type="primary"):
        alternatives = [
            "Створити короткий конспект із ключовими поняттями.",
            "Створити практичну вправу з перевіркою помилок.",
            "Створити набір тестових запитань різної складності.",
            "Адаптувати матеріал під різний рівень підготовки.",
            "Створити сценарій навчальної ситуації з контрольними питаннями.",
        ]
        st.session_state["alternatives"] = alternatives
        st.session_state["task"] = task

    alternatives = st.session_state.get("alternatives", [])
    if alternatives:
        st.markdown("### Варіанти без ранжування")
        for i, item in enumerate(alternatives, 1):
            st.write(f"**{i}.** {item}")

        st.divider()
        st.markdown("### 🔴 Оцінювання")
        cols = st.columns(4)
        criteria = ["Ризик", "Реалізованість", "Час", "Перевірюваність"]
        values = {}
        for col, criterion in zip(cols, criteria):
            with col:
                values[criterion] = st.slider(criterion, 0, 10, 5)

        if st.button("Перейти до критичної перевірки"):
            st.session_state["evaluation"] = values
            st.success("Оцінювання збережено. Наступний крок — знайти слабкі місця.")

elif page == "Перевірка":
    st.subheader("🔎 Критична перевірка")
    st.caption("Мета — не довести, що ідея правильна, а перевірити, що ми могли пропустити.")

    sections = {
        "Сильні сторони": "Що працює добре?",
        "Слабкі сторони": "Що може не спрацювати?",
        "Припущення": "Що ми прийняли за правду без перевірки?",
        "Суперечності": "Чи конфліктують між собою твердження?",
        "Пропущені ризики": "Які ризики ми ще не врахували?",
        "Альтернативні пояснення": "Чи є інше пояснення тієї самої ситуації?",
        "Невідомі дані": "Якої інформації нам не вистачає?",
    }
    for title, question in sections.items():
        with st.expander(title):
            st.write(question)
            st.text_area("Відповідь", key=f"check_{title}")

    st.divider()
    st.markdown("### ✅ Checklist")
    checks = [
        "Задача сформульована зрозуміло",
        "Є щонайменше 5 альтернатив",
        "Варіанти не оцінювалися під час генерації",
        "Ризики визначені",
        "Припущення визначені",
        "Невідомі дані позначені",
        "Ключові факти перевірені",
        "Результат перевірений людиною",
    ]
    for item in checks:
        st.checkbox(item)

    st.warning("Фінальне рішення не генерується автоматично. Користувач сам підтверджує результат після перевірки.")

elif page == "Мій прогрес":
    st.subheader("📊 Мій прогрес")
    st.markdown("### Поточні навички")
    rows = [
        ("Постановка задач", 76),
        ("Контекст і обмеження", 68),
        ("Генерація альтернатив", 54),
        ("Критичне мислення", 48),
        ("Перевірка фактів", 61),
        ("Оцінка ризику", 37),
    ]
    for name, score in rows:
        st.write(f"**{name} — {score}%**")
        st.progress(score / 100)

    st.markdown("### Наступна рекомендована вправа")
    st.info("Знайти припущення та пропущені ризики у готовому AI-рішенні.")

st.divider()
st.caption("MVP-прототип. Навчальний матеріал і правила використання мають бути перевірені відповідальними фахівцями перед впровадженням.")
